func levelColumn(level Level) int {
	switch level {
	case LevelL:
		return 0
	case LevelM:
		return 1
	case LevelQ:
		return 2
	case LevelH:
		return 3
	default:
		return -1
	}
}

func dataCapacity(version int, level Level) int {
	col := levelColumn(level)
	if col < 0 || version < 1 || version > 40 {
		return 0
	}
	return versionCapacities[version-1][col]
}
